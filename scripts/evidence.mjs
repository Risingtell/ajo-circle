// Re-checks every recorded Ajo Circle transaction against the chain and prints a Markdown report:
// receipt status, sender, and the USDC that moved into and out of the circle. Read-only.
// Usage: node scripts/evidence.mjs [--testnet] > EVIDENCE.md
import { readFileSync } from "node:fs";
import { createPublicClient, http, formatUnits, getAddress, toEventSelector } from "viem";

const testnet = process.argv.includes("--testnet");
const rpc = testnet ? "https://rpc.testnet.arc.io" : "https://rpc.mainnet.arc.io";
const explorer = testnet ? "https://explorer.testnet.arc.io" : "https://explorer.arc.io";
const network = testnet ? "Arc testnet" : "Arc mainnet";
const state = JSON.parse(readFileSync(`deployments/${testnet ? "testnet" : "mainnet"}.json`, "utf8"));
const client = createPublicClient({ transport: http(rpc) });

// Arc logs every USDC transfer twice: from the system emitter in 18 decimals and from the
// USDC ERC-20 interface in 6 decimals. Count only the ERC-20 interface's log.
const USDC = "0x3600000000000000000000000000000000000000";
const TRANSFER = toEventSelector("Transfer(address,address,uint256)");
const circle = getAddress(state.circle);
const short = (a) => `${a.slice(0, 6)}...${a.slice(-4)}`;

const steps = [{ label: "deploy AjoFactory", hash: state.factoryTx }, ...state.txs];
let into = 0n;
let out = 0n;
let ok = 0;
const rows = [];
for (const step of steps) {
  const [receipt, tx] = await Promise.all([client.getTransactionReceipt({ hash: step.hash }), client.getTransaction({ hash: step.hash })]);
  if (receipt.status === "success") ok++;
  let moved = 0n;
  for (const log of receipt.logs) {
    if (getAddress(log.address) !== getAddress(USDC) || log.topics[0] !== TRANSFER) continue;
    const from = getAddress("0x" + log.topics[1].slice(26));
    const to = getAddress("0x" + log.topics[2].slice(26));
    const amount = BigInt(log.data);
    if (to === circle) { into += amount; moved += amount; }
    if (from === circle) { out += amount; moved += amount; }
  }
  rows.push(`| ${step.label} | ${short(tx.from)} | ${receipt.status} | ${moved ? formatUnits(moved, 6) : ""} | [${short(step.hash)}](${explorer}/tx/${step.hash}) |`);
}

const s = await client.readContract({
  address: circle,
  abi: JSON.parse(readFileSync("studio/contracts/out/AjoCircle.sol/AjoCircle.json", "utf8")).abi,
  functionName: "circleState",
});
const held = await client.readContract({ address: USDC, abi: [{ type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ type: "address" }], outputs: [{ type: "uint256" }] }], functionName: "balanceOf", args: [circle] });

console.log(`# Ajo Circle on ${network}\n`);
console.log(`Generated by \`node scripts/evidence.mjs${testnet ? " --testnet" : ""}\`, which re-reads every transaction below from the chain.\n`);
console.log(`- AjoFactory: [${state.factory}](${explorer}/address/${state.factory})`);
console.log(`- Circle "${s.name}": [${circle}](${explorer}/address/${circle})`);
console.log(`- ${s.members.length} members, ${formatUnits(s.contribution, 6)} USDC a round, ${s.roundPaidOut.filter(Boolean).length} of ${s.members.length} rounds paid out, finished: ${s.finished}`);
console.log(`- ${ok} of ${steps.length} transactions succeeded`);
console.log(`- USDC paid into the circle: ${formatUnits(into, 6)} (deposits and contributions)`);
console.log(`- USDC paid out of the circle: ${formatUnits(out, 6)} (pots collected and deposits returned)`);
console.log(`- USDC the circle holds now: ${formatUnits(held, 6)}\n`);
console.log("| Step | From | Status | USDC through the circle | Transaction |");
console.log("| --- | --- | --- | --- | --- |");
for (const row of rows) console.log(row);
